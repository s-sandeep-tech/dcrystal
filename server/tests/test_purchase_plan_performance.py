def parity_cases(calculator):
    results = []
    for cutoff, filters in [
        (None, {}),
        (date(2026, 9, 29), {}),
        (date(2026, 9, 30), {'division': ['GOLD']}),
        (None, {'branch_type': ['SHOP'], 'branch_status': ['Active']}),
        (None, {'branch_id': ['1', '2']}),
        (None, {'branch_id': ['999']}),
    ]:
        for root in HIERARCHY:
            for sort_by, sort_order in [('label', 'asc'), ('shop_weight_turn', 'desc')]:
                kwargs = dict(hierarchy_root=root, sort_by=sort_by, sort_order=sort_order)
                result = calculator(cutoff, filters, **kwargs)
                results.append(result)
                if result['rows']:
                    path = [result['rows'][0]['label']]
                    results.append(calculator(cutoff, filters, path=path, **kwargs))
                    results.append(calculator(cutoff, filters, path=path,
                                              contributors=True, hierarchy_root=root))
    return results


class PurchasePlanPerformanceTests(unittest.TestCase):
    def setUp(self):
        self.app = Flask(__name__)
        self.app.config['SQLALCHEMY_DATABASE_URI'] = 'sqlite:///:memory:'
        db.init_app(self.app)
        self.ctx = self.app.app_context()
        self.ctx.push()
        Snapshot.__table__.create(db.engine)
        seed()
        self.redis = MemoryRedis()
        self.redis_patch = patch.object(cache, 'redis_client', self.redis)
        self.redis_patch.start()
        self.statements = []
        self.listener = lambda conn, cursor, statement, parameters, context, many: self.statements.append(statement)
        event.listen(db.engine, 'before_cursor_execute', self.listener)

    def tearDown(self):
        event.remove(db.engine, 'before_cursor_execute', self.listener)
        self.redis_patch.stop()
        db.session.remove()
        self.ctx.pop()

    def test_pre_optimization_value_parity(self):
        # Fingerprint generated by the original service on this exact fixture;
        # checks every returned value across roots, sorts, paths and charts.
        expected = '37e13b54a27c9fe29b1834e5bec83f19fde879675e42f51f60848bfcb5376fb4'
        results = parity_cases(calculate)
        self.assertEqual(hashlib.sha256(json.dumps(results, sort_keys=True).encode()).hexdigest(), expected)
        with self.app.test_request_context():
            cached = parity_cases(lambda *a, **kw: calculate(*a, **kw, cache_shared=True))
        self.assertEqual(results, cached)
        # Repeat through JSON-deserialized cache hits, not just fresh builds.
        with self.app.test_request_context():
            self.assertEqual(results, parity_cases(lambda *a, **kw: calculate(*a, **kw, cache_shared=True)))

    def test_query_budget_and_shared_totals_across_paths_and_sort(self):
        cutoff = date(2026, 9, 30)
        self.statements.clear()
        baseline = calculate(cutoff, {})
        self.assertEqual(len(self.statements), 5)  # Previously seven SQL queries.
        with self.app.test_request_context():
            self.assertEqual(baseline, calculate(cutoff, {}, cache_shared=True))
        self.statements.clear()
        with self.app.test_request_context():
            result = calculate(cutoff, {}, path=['CHAIN'], sort_order='desc', cache_shared=True)
        self.assertEqual(len(self.statements), 3)  # Version + two child aggregates.
        self.assertEqual(result['total'], baseline['total'])
        self.assertEqual(result['stats'], baseline['stats'])

    def test_options_cache_refresh_and_failure(self):
        def read():
            with self.app.test_request_context():
                return cache.cached_purchase_plan_value('options', [], get_purchase_plan_options)
        original = read()
        self.statements.clear()
        self.assertEqual(read(), original)
        self.assertEqual(len(self.statements), 1)
        snapshot = db.session.get(Snapshot, 1)
        snapshot.section = 'NEW SECTION'
        snapshot.synced_at = datetime(2026, 10, 2)
        db.session.commit()
        self.assertIn('NEW SECTION', read()['sections'])
        with patch.object(self.redis, 'get', side_effect=RedisConnectionError('offline')):
            self.assertEqual(read(), get_purchase_plan_options())

    def test_single_flight_wait_reads_other_workers_result(self):
        with self.app.test_request_context(), patch.object(self.redis, 'set', return_value=False), patch.object(
            self.redis, 'get', side_effect=[None, json.dumps({'value': 42})]
        ), patch.object(cache.time, 'sleep'), patch.object(cache, '_record') as record:
            result = cache.cached_purchase_plan_value('test', [], lambda: self.fail('Duplicate rebuild'))
        self.assertEqual(result, {'value': 42})
        record.assert_any_call('hits')

    def test_failed_build_releases_lock_and_does_not_cache_error(self):
        def failed():
            raise ValueError('database failure')
        with self.app.test_request_context(), self.assertRaises(ValueError):
            cache.cached_purchase_plan_value('test', [], failed)
        self.assertFalse(self.redis.entries)

    def test_empty_snapshot_never_serves_previous_cache(self):
        with self.app.test_request_context():
            cache.cached_purchase_plan_value('options', [], get_purchase_plan_options)
        Snapshot.query.delete()
        db.session.commit()
        with self.app.test_request_context():
            result = cache.cached_purchase_plan_value('options', [], get_purchase_plan_options)
        self.assertEqual(result['sections'], [])

    def test_cache_outage_is_only_attempted_once_per_request(self):
        with self.app.test_request_context(), patch.object(
            self.redis, 'get', side_effect=RedisConnectionError('offline')
        ) as read:
            expected = calculate(date(2026, 9, 30), {})
            result = cache.cached_purchase_plan_data(
                date(2026, 9, 30), {}, [], 'label', 'asc', 'section',
                lambda: calculate(date(2026, 9, 30), {}, cache_shared=True))
            self.assertEqual(result, expected)
            self.assertEqual(read.call_count, 1)

    def test_timing_logs_query_and_cache_counts(self):
        @cache.measure_purchase_plan('test')
        def measured():
            return cache.cached_purchase_plan_value('options', [], get_purchase_plan_options)
        with self.app.test_request_context(), self.assertLogs(cache.logger, level='INFO') as logs:
            measured()
            measured()
        self.assertIn('cache_misses=1', logs.output[0])
        self.assertIn('sql_queries=10', logs.output[0])
        self.assertIn('cache_hits=1', logs.output[1])
        self.assertIn('sql_queries=0', logs.output[1])
